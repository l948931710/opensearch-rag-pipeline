_LITERAL_RE = re.compile(r"RAG_[A-Z0-9_]+")
_ENV_HELPER_RE = re.compile(r"_env(?:_bool|_int|_float)?\(\s*[\"']([A-Z0-9_]+)[\"']")
_SELF = "rag_env_registry.py"


def scan_source_rag_vars(repo_root: Path) -> Set[str]:
    """按上方口径扫描源码，返回全部 RAG_* 名（测试/__main__ 用；运行时不调用——
    SAE 包内不保证六根齐全，运行时只消费冻结的 KNOWN_RAG_ENV_VARS）。"""
    names: Set[str] = set()
    for root in SCAN_ROOTS:
        base = repo_root / root
        if not base.is_dir():
            continue
        for p in base.rglob("*.py"):
            if p.name == _SELF:
                continue
            try:
                text = p.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            names.update(_LITERAL_RE.findall(text))
            if root == "opensearch_pipeline" and p.name == "config.py":
                names.update(f"RAG_{m}" for m in _ENV_HELPER_RE.findall(text))
    return names


def unknown_rag_vars() -> Set[str]:
    """当前进程环境里「设了但不被任何代码消费」的 RAG_* 名。"""
    return {k for k in os.environ if k.startswith("RAG_")} - KNOWN_RAG_ENV_VARS


